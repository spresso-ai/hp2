"""Generates HP2RpgHP1Lines.h: Harry Potter 1 voice lines that have both a
sound in H1AllDialog and a subtitle in H1Dialog.int, grouped by who says
them and what kind of line it is.

  python3 -I gen_lines.py <HP2 Data/Unreal dir> <out.h>
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from m212 import Pkg

# (category, key regex, keep plain text). Order matters: first match wins.
CATS = [
    ('H1_Student',   r'^(STUDENT_\d+|\d+Student(Boy|Girl|boy|girl)\w*|student\w*)$'),
    ('H1_Nick',      r'^nearly_nick_\d+$'),
    ('H1_Peeves',    r'^\d+Peeves\d+$'),
    ('H1_Neville',   r'^neville_hall_\d+$'),
    ('H1_Dumbledore', r'^\d+DumbledoreInfo\d+$'),
    ('H1_Lee',       r'^\d+(LeeJordan|commentary|Commentary)\d+$'),
    ('H1_Hooch',     r'^(\d+Extra\d+|113Hooch_Emotives\d+)$'),
    ('H1_Filch',     r'^FILCH_0\d$'),
    ('H1_Malfoy',    r'^(125Malfoy_Emotives\d+|MALFOY_00[25])$'),
    ('H1_Prefect',   r'^prefect_new_\d+$'),
    ('H1_Points',    r'^(SPROUT|FLITWICK)_\d+$'),
    ('H1_EmoRon',    r'^EmotiveRon\d+$'),
    ('H1_EmoHarry',  r'^EmotiveHarry\d+$'),
    ('H1_EmoPeeves', r'^EmotivePeeves\d+$'),
    ('H1_EmoSnape',  r'^EmotiveSnape\d+$'),
    ('H1_EmoFilch',  r'^EmotiveFilch\d+$'),
    ('H1_EmoFlitwick', r'^EmotiveFlitwick\d+$'),
    ('H1_EmoQuirrell', r'^EmotiveQuirrel\d+$'),
]
# Lines that only make sense inside HP1's story.
PLOT = re.compile(r'troll|Remembrall|Norbert|dragon egg|Fluffy|third floor|off limits|first[- ]year|seeker|Halloween|'
                  r'follow me|follow us|lesson|challenge|this door|next room|press|keys|<|arrow|mouse|menu|'
                  r'Voldemort|Philosopher|Stone|Snape gives|portrait door|save game|your game|stamina', re.I)
POINTS = re.compile(r'points (for|from) Gryffindor', re.I)


def main(H, out):
    pk = Pkg(os.path.join(H, 'Sounds', 'H1AllDialog.uax'))
    have = {pk.names[e['name']][0] for e in pk.exps if pk.cname(e) == 'Sound'}
    text = {}
    for l in open(os.path.join(H, 'System', 'H1Dialog.int'), encoding='latin1').read().replace('\r', '').split('\n'):
        if '=' in l and not l.startswith('['):
            k, v = l.split('=', 1)
            text.setdefault(k.strip(), v.strip())
    rows = []
    for k in sorted(text):
        if k not in have:
            continue
        for cat, rx in CATS:
            if re.match(rx, k):
                t = text[k]
                emo = cat.startswith('H1_Emo') or t.upper().startswith('EMOTIVE')
                if cat == 'H1_Points':
                    if not POINTS.search(t):
                        break
                elif not emo and cat not in ('H1_Lee', 'H1_Hooch', 'H1_Malfoy') and PLOT.search(t):
                    break
                rows.append((cat, k, '' if emo else t))
                break
    cats = [c for c, _ in CATS]
    with open(out, 'w') as f:
        f.write('/*=============================================================================\n')
        f.write('\tHP2RpgHP1Lines.h: Harry Potter 1 voice lines (H1AllDialog sounds with\n')
        f.write('\ttheir H1Dialog.int subtitles). Generated by hp1/gen_lines.py.\n')
        f.write('=============================================================================*/\n\n')
        f.write('enum EH1LineCat { %s, H1_MAX };\n\n' % ', '.join(cats))
        f.write('struct FH1Line { BYTE Cat; const TCHAR* Sound; const TCHAR* Text; };\n\n')
        f.write('static const FH1Line GH1Lines[] =\n{\n')
        for cat, k, t in rows:
            t = t.replace('\\', '\\\\').replace('"', '\\"').replace('  ', ' ')
            f.write('\t{ %s, TEXT("%s"), TEXT("%s") },\n' % (cat, k, t))
        f.write('};\nstatic const INT GNumH1Lines = (INT)ARRAY_COUNT(GH1Lines);\n')
    import collections
    print(collections.Counter(c for c, _, _ in rows))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
